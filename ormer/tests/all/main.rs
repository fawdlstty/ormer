//! 集成测试统一入口：`tests/all/` 下每个测试文件作为一个模块编入同一个测试二进制。
//!
//! 原先 130+ 个测试文件各自编译为独立二进制，`cargo test` 需要逐个启动进程
//! （每个约 107MB、进程启动开销 1s+），这是全量测试耗时的主导项；合并后
//! 676 个测试在同一进程内以线程并行执行，进程开销只剩一份。
//! 模块清单由 `build.rs` 扫描本目录自动生成，新增测试文件放入本目录即可。

#[macro_use]
mod _test_common;

include!(concat!(env!("OUT_DIR"), "/all_tests.rs"));
